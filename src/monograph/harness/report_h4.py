"""Build docs/h4/RESULTS.md from results/h4/*.jsonl alone.

The scoring run is the one that wrote the latest `h4.aggregate` for the split; every table comes from
that run's lines. The verdict and the PoV section are computed from those numbers by the
pre-registered rules, which are printed next to them.
"""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Iterable
from typing import Any

from monograph.extract.config import ALL_ARMS, MODELS, UPPER_BOUND_ARMS
from monograph.extract.score import THRESHOLD

Record = dict[str, Any]


def _f(value: Any, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _pct(value: Any) -> str:
    return "n/a" if value is None else f"{float(value) * 100:.1f}%"


def _usd(value: Any) -> str:
    return "n/a" if value is None else f"${float(value):.4f}"


def _table(header: list[str], rows: Iterable[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in row) + " |" for row in rows]
    return out


class H4Report:
    def __init__(self, records: list[Record], split: str = "test") -> None:
        self._all = sorted(records, key=lambda r: r["timestamp"])
        self._split = split
        aggregates = [r for r in self._all if r["metric"] == "h4.aggregate" and r["details"]["split"] == split]
        self._run = aggregates[-1]["run_id"] if aggregates else None
        self._lines = [r for r in self._all if r["run_id"] == self._run]

    def _metric(self, name: str) -> list[Record]:
        return [r for r in self._lines if r["metric"] == name]

    def _agg(self, model: str, arm: str, group: str) -> dict[str, Any] | None:
        for r in self._metric("h4.aggregate"):
            d = r["details"]
            if (d["model"], d["arm"], d["group"]) == (model, arm, group):
                found: dict[str, Any] = d
                return found
        return None

    # -----------------------------------------------------------------------------------------------

    def render(self) -> str:
        out = [
            "# H4 results: LLM extraction is usable only with SHACL repair",
            "",
            f"Generated by `monograph report h4` from `results/h4/*.jsonl` only. Split: `{self._split}`. Scoring run:"
            f" `{self._run}`. Do not edit by hand.",
            "",
        ]
        if self._run is None:
            return "\n".join([*out, "No scoring run recorded yet. Run `monograph h4 score`.", ""])
        out += self._threshold()
        out += self._headline()
        out += self._differences()
        out += self._cost()
        out += self._attribution()
        out += self._gap()
        out += self._strata()
        out += self._errors()
        out += self._deviations()
        out += self._pov()
        return "\n".join(out).rstrip() + "\n"

    def _threshold(self) -> list[str]:
        verdict = self._metric("h4.verdict")
        out = [
            "## Pre-registered threshold and verdict",
            "",
            "A configuration is usable if, on the headline test labels (every label outside the allergenic"
            " stratum), all of these hold:",
            "",
            f"* mean per-label ingredient-strength F1 >= {THRESHOLD['mean_f1']}",
            f"* dosage form accuracy >= {THRESHOLD['dosage_form_accuracy']}"
            f" and route accuracy >= {THRESHOLD['route_accuracy']}",
            f"* unresolvable reference rate <= {THRESHOLD['unresolvable_rate']:.0%}",
            f"* hallucination rate <= {THRESHOLD['hallucination_rate']:.1%}",
            "",
            "Decision rule (arms A0 to A3 only; A3+ is an upper bound outside it): **fails** if A1 or A2 is usable"
            " for every model (evaluated first); **holds** if, for at least one model, A3 is usable and A2 is not;"
            " otherwise **partly holds**.",
            "",
        ]
        if verdict:
            out += [f"**Verdict: H4 {verdict[-1]['value']}.**", ""]
            usable = verdict[-1]["details"]["usable"]
            out += _table(["Configuration", "Usable"], [[k, "yes" if v else "no"] for k, v in sorted(usable.items())])
        else:
            out += [f"No verdict for split `{self._split}` (the verdict is computed on test only)."]
        return [*out, ""]

    def _headline(self) -> list[str]:
        rows = []
        for model in MODELS:
            for arm in ALL_ARMS:
                a = self._agg(model, arm, "headline")
                if a is None:
                    continue
                checks = a.get("checks") or {}
                failing = [k for k, ok in checks.items() if not ok]
                rows.append(
                    [
                        model,
                        arm + (" (upper bound)" if arm in UPPER_BOUND_ARMS else ""),
                        a["labels"],
                        f"{_f(a['mean_f1'])} [{_f(a.get('mean_f1_ci_low'))}, {_f(a.get('mean_f1_ci_high'))}]",
                        _f(a["pooled_f1"]),
                        _f(a["dosage_form_accuracy"]),
                        _f(a["route_accuracy"]),
                        _pct(a["unresolvable_rate"]),
                        _pct(a["hallucination_rate"]),
                        _pct(a["exact_match_rate"]),
                        _pct(a["violation_free_rate"]),
                        _pct(a.get("refusal_rate")),
                        _pct(a.get("truncation_rate")),
                        a.get("other_strengths", 0),
                        "yes" if a.get("usable") else "no: " + ", ".join(failing),
                    ]
                )
        out = ["## Model x arm (headline labels)", "", "Mean per-label F1 with its 95% bootstrap interval.", ""]
        out += _table(
            [
                "Model",
                "Arm",
                "Labels",
                "Mean F1 [95% CI]",
                "Pooled F1",
                "Form acc",
                "Route acc",
                "Unresolvable",
                "Hallucinated",
                "Exact match",
                "Violation-free",
                "Refused",
                "Truncated",
                "Other strengths",
                "Usable",
            ],
            rows,
        )
        return [*out, ""]

    def _differences(self) -> list[str]:
        rows = [
            [
                d["details"]["comparison"],
                d["details"].get("labels"),
                _f(d["details"].get("difference")),
                f"[{_f(d['details'].get('ci_low'))}, {_f(d['details'].get('ci_high'))}]",
            ]
            for d in self._metric("h4.difference")
        ]
        out = [
            "## Arm and model differences",
            "",
            "Paired bootstrap over labels of the difference in mean per-label F1.",
            "",
        ]
        return [*out, *_table(["Comparison", "Labels", "Difference", "95% CI"], rows), ""]

    def _cost(self) -> list[str]:
        rows = []
        for model in MODELS:
            for arm in ALL_ARMS:
                a = self._agg(model, arm, "headline")
                if a is None:
                    continue
                u = a["usage"]
                rows.append(
                    [
                        model,
                        arm,
                        _f(a["mean_repair_rounds"], 2),
                        u["input_tokens"],
                        u["output_tokens"],
                        u["cache_read_tokens"],
                        u["cache_write_tokens"],
                        _usd(a["cost_usd"]),
                        _usd(a["cost_per_record_usd"]),
                        _usd(a["cost_per_usable_record_usd"]),
                        _f(a["latency_p50_s"], 1),
                        _f(a["latency_p95_s"], 1),
                    ]
                )
        out = [
            "## Cost and latency",
            "",
            "Per configuration as if run alone (rounds shared through the response cache are counted in every arm"
            " that uses them). A usable record is an exact-match record.",
            "",
        ]
        out += _table(
            [
                "Model",
                "Arm",
                "Repair rounds",
                "Input",
                "Output",
                "Cache read",
                "Cache write",
                "Cost",
                "Per record",
                "Per usable record",
                "p50 s",
                "p95 s",
            ],
            rows,
        )
        return [*out, ""]

    def _attribution(self) -> list[str]:
        rows = []
        for r in self._metric("h4.attribution"):
            d = r["details"]
            rows.append(
                [
                    d["model"],
                    d["arm"],
                    d["first_round_errors"],
                    d["final_errors"],
                    d.get("fixed_by", {}),
                    d.get("regressions_by", {}),
                    d["graph_fixes_with_gold_in_feedback"],
                ]
            )
        out = [
            "## Repair attribution",
            "",
            "Field errors (gold ingredient tuples, product forms and routes, printed NDCs) after the first round and"
            " after the last, which kind of step fixed each error, and how many correct fields a step broke. The"
            " last column counts graph-context fixes whose gold value appeared anywhere in the preceding feedback."
            " Under A3 that happens only when the gold value also exists in a source independent of the label (a"
            " common substance named by other labels or DailyMed's moiety list); the feedback audit below checks"
            " every value actually sent.",
            "",
        ]
        out += _table(
            [
                "Model",
                "Arm",
                "Errors after round 0",
                "Errors at the end",
                "Fixed by",
                "Regressions by",
                "Graph fixes with gold in feedback",
            ],
            rows,
        )
        out += [
            "",
            "### Feedback audit",
            "",
            "Every allowed value sent in graph-context feedback, checked against the label it was offered for."
            " Label-only: the value has no source except the label's own SPL, DailyMed NDC list or NDC directory"
            " records. Must be 0 for A3; A3+ offers label-derived values by design.",
            "",
        ]
        latest: dict[tuple[str, str], Record] = {}
        for r in self._all:
            if r["metric"] == "h4.feedback_audit" and r["details"]["split"] == self._split:
                latest[(r["details"]["model"], r["details"]["arm"])] = r
        if latest:
            out += _table(
                ["Model", "Arm", "Values offered", "Label-only", "Unmatched pieces"],
                [
                    [m, a, r["details"]["offered"], r["details"]["label_only"], r["details"]["unmatched"]]
                    for (m, a), r in sorted(latest.items())
                ],
            )
        else:
            out.append("Not run. Run `monograph h4 audit-feedback`.")
        return [*out, ""]

    def _gap(self) -> list[str]:
        rows = [
            [r["details"]["model"], r["details"]["arm"], r["value"], r["details"]["products_in_split"]]
            for r in self._metric("h4.gap")
        ]
        out = [
            "## The H6 gap",
            "",
            "121 openFDA products failed H6 on ingredient pairing. 39 of them have an SPL on DailyMed; the others are"
            " bulk ingredients, drugs for further processing or vaccine bulk intermediates, which DailyMed does not"
            " publish. A gap product counts as resolved when its gold ingredient tuples are extracted exactly.",
            "",
        ]
        return [*out, *_table(["Model", "Arm", "Gap products resolved", "Gap products in this split"], rows), ""]

    def _strata(self) -> list[str]:
        groups: dict[str, list[list[Any]]] = defaultdict(list)
        for r in self._metric("h4.aggregate"):
            d = r["details"]
            if d["group"].startswith("stratum:") or d["group"] == "h6_gap":
                groups[d["group"]].append(
                    [
                        d["model"],
                        d["arm"],
                        d["labels"],
                        _f(d["mean_f1"]),
                        _f(d["dosage_form_accuracy"]),
                        _f(d["route_accuracy"]),
                        _pct(d["exact_match_rate"]),
                        _pct(d.get("truncation_rate")),
                    ]
                )
        out = [
            "## Per stratum",
            "",
            "The allergenic stratum (labels of standardized or non-standardized allergenic extracts) is reported here"
            " and in the H6 gap section, outside the headline threshold: one product type would otherwise dominate"
            " the pooled metrics. The h6_gap group includes the allergenic gap labels, whose hundreds of products"
            " dominate its product-pooled form and route accuracy; the H6 gap section counts gap products one by one.",
            "",
        ]
        for group in sorted(groups):
            out += [f"### {group.removeprefix('stratum:')}", ""]
            out += _table(
                ["Model", "Arm", "Labels", "Mean F1", "Form acc", "Route acc", "Exact match", "Truncated"],
                groups[group],
            )
            out.append("")
        return out

    def _errors(self) -> list[str]:
        out = ["## Top residual error patterns", "", "Final-round errors on the headline labels, one example each.", ""]
        for r in self._metric("h4.errors"):
            d = r["details"]
            if d["arm"] not in ("A3", "A2"):
                continue
            out += [f"### {d['model']} {d['arm']}", ""]
            out += _table(
                ["Pattern", "Count", "Example label", "Example"],
                [[p["pattern"], p["count"], p["example"]["set_id"][:8], p["example"]["detail"]] for p in d["patterns"]],
            )
            out.append("")
        return out

    def _deviations(self) -> list[str]:
        devs = [r for r in self._all if r["metric"] == "h4.deviation"]
        out = ["## Deviations after pre-registration", ""]
        if not devs:
            return [*out, "None.", ""]
        return [*out, *(f"* {d['timestamp'][:19]}: {d['value']} ({d['details']})" for d in devs), ""]

    def _pov(self) -> list[str]:
        out = ["## What this means for the PoV", ""]
        verdict = self._metric("h4.verdict")
        if not verdict:
            return [*out, "No test verdict yet.", ""]
        lines = [f"* Verdict: H4 {verdict[-1]['value']} under the pre-registered rule."]
        for model in MODELS:
            a2, a3, a3p = (self._agg(model, arm, "headline") for arm in ("A2", "A3", "A3+"))
            if a2 is None or a3 is None:
                continue
            gain = a3["mean_f1"] - a2["mean_f1"]
            cost_a2, cost_a3 = float(a2["cost_per_record_usd"]), float(a3["cost_per_record_usd"])
            extra = cost_a3 - cost_a2
            lines.append(
                f"* {model}: graph-context repair moves mean F1 from {_f(a2['mean_f1'])} (A2)"
                f" to {_f(a3['mean_f1'])} (A3),"
                f" a change of {gain:+.3f}, for {_usd(extra)} more per record"
                f" ({_usd(cost_a2)} to {_usd(cost_a3)}). Usable: A2 {'yes' if a2.get('usable') else 'no'},"
                f" A3 {'yes' if a3.get('usable') else 'no'}."
                + (f" With label-derived candidates (A3+, upper bound) mean F1 is {_f(a3p['mean_f1'])}." if a3p else "")
            )
        cheap = MODELS[-1]
        a3_cheap = self._agg(cheap, "A3", "headline")
        if a3_cheap is not None:
            failing = [k for k, ok in (a3_cheap.get("checks") or {}).items() if not ok]
            lines.append(
                f"* Does graph-context repair let the cheaper model ({cheap}) reach the threshold? "
                + ("Yes." if a3_cheap.get("usable") else f"No; still failing: {', '.join(failing)}.")
            )
        return [*out, *lines, ""]
