"""Build docs/MUTATIONS.md from results/mutations/*.jsonl alone: the latest run of each mutation, the gate
that caught it, and the date and commit of that run.

The page is a status page, not an experiment report: it belongs to no hypothesis, and it is regenerated
(by `monograph report mutations`, and on every CI mutation run) rather than edited.
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from typing import Any

Record = dict[str, Any]

PREFIX = "mutation.M"
CONTROL = "none (must pass)"  # the expected gate of a probe that must pass every gate


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _number(metric: str) -> int:
    match = re.fullmatch(r"mutation\.M(\d+)", metric)
    return int(match.group(1)) if match else -1


def _commit(sha: str) -> str:
    """The short SHA, keeping a `-dirty` mark."""
    base, dirty, _ = sha.partition("-dirty")
    return base[:7] + ("-dirty" if dirty else "")


def outcome(details: dict[str, Any]) -> str:
    """What the run showed, from the recorded fields alone."""
    failed = details.get("failed_gates") or []
    if details.get("apply_error"):
        return "could not apply"
    if details.get("expected_gate") == CONTROL:
        return "passed every gate" if not failed else "false alarm"
    expected = str(details.get("expected_gate", "")).split("|")
    if any(g in failed for g in expected):
        return "caught"
    return "caught by another gate" if failed else "missed"


def latest_per_mutation(records: Iterable[Record]) -> list[Record]:
    """The latest line of each mutation, by timestamp, in mutation order."""
    latest: dict[str, Record] = {}
    for r in sorted(records, key=lambda r: r["timestamp"]):
        if _number(r["metric"]) >= 0:
            latest[r["metric"]] = r
    return [latest[m] for m in sorted(latest, key=_number)]


def render(records: list[Record]) -> str:
    rows = latest_per_mutation(records)
    lines = [
        "# Mutation suite status",
        "",
        "Generated by `monograph report mutations` from `results/mutations/*.jsonl` alone; do not edit by hand.",
        "Each row is the latest recorded run of that mutation. *Caught by* lists every gate that failed;",
        "*Outcome* is `caught` when one of them is the expected gate, and `passed every gate` for a control",
        "probe that must not trip any gate.",
        "",
    ]
    if not rows:
        return "\n".join([*lines, "No mutation runs are recorded yet.", ""])
    header = ["Mutation", "What it breaks", "Expected gate", "Caught by", "Outcome", "Date (UTC)", "Commit"]
    lines += ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for r in rows:
        d = r["details"]
        cells = [
            r["metric"].removeprefix("mutation."),
            d.get("title", ""),
            d.get("expected_gate", ""),
            ", ".join(d.get("failed_gates") or []) or "none",
            outcome(d),
            r["timestamp"][:10],
            _commit(r.get("git_sha", "unknown")),
        ]
        lines.append("| " + " | ".join(_cell(c) for c in cells) + " |")
    bad = [r["metric"].removeprefix("mutation.") for r in rows if outcome(r["details"]) not in _GOOD]
    lines += [
        "",
        f"{len(rows)} mutations; "
        + ("every one ended as expected in its latest run." if not bad else f"not as expected: {', '.join(bad)}."),
        "",
    ]
    return "\n".join(lines)


_GOOD = ("caught", "passed every gate")
