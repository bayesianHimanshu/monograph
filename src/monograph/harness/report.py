"""Build docs/h6/RESULTS.md from results/h6/*.jsonl alone.

For each metric the latest line wins. Mutation lines are taken from the run that wrote the latest
`mutation.detection_rate`, so the table is one consistent suite run. The verdict in the last section is
computed from the numbers by fixed rules, which are printed next to it.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable
from typing import Any

Record = dict[str, Any]


def _pct(value: Any) -> str:
    return "n/a" if value is None else f"{float(value) * 100:.1f}%"


def _cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: Iterable[list[Any]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines


class ReportBuilder:
    def __init__(self, records: list[Record]) -> None:
        self._records = sorted(records, key=lambda r: r["timestamp"])
        self._latest: dict[str, Record] = {}
        for r in self._records:
            self._latest[r["metric"]] = r

    def _get(self, metric: str) -> Record | None:
        return self._latest.get(metric)

    def _value(self, metric: str) -> Any:
        r = self._get(metric)
        return None if r is None else r["value"]

    def _details(self, metric: str) -> dict[str, Any]:
        r = self._get(metric)
        return {} if r is None else dict(r["details"])

    def _mutations(self) -> list[Record]:
        summary = self._get("mutation.detection_rate")
        if summary is None:
            return []
        run = summary["run_id"]
        rows = [r for r in self._records if r["run_id"] == run and r["metric"].startswith("mutation.M")]
        return sorted(rows, key=lambda r: int(r["metric"].removeprefix("mutation.M")))

    # -----------------------------------------------------------------------------------------------

    def render(self) -> str:
        out: list[str] = []
        runs = Counter(r["run_id"] for r in self._records)
        out += [
            "# H6 results: one schema keeps OWL, SHACL and Pydantic in sync",
            "",
            "Generated by `monograph report h6` from `results/h6/*.jsonl` only. Do not edit by hand.",
            f"Source: {len(self._records)} result lines from {len(runs)} run{'s' if len(runs) != 1 else ''}."
            " For each metric the latest line is used.",
            "",
        ]
        out += self._summary()
        out += self._mutation_section()
        out += self._agreement_section()
        out += self._roundtrip_section()
        out += self._conformance_section()
        out += self._leak_section()
        out += self._size_section()
        out += self._provenance()
        out += self._pov()
        return "\n".join(out).rstrip() + "\n"

    def _summary(self) -> list[str]:
        rows = [
            ["Mutation detection by the expected gate", _pct(self._value("mutation.detection_rate"))],
            ["Pydantic and SHACL agreement, curated fixtures", _pct(self._value("agreement.fixtures"))],
            ["Pydantic and SHACL agreement, property-based cases", _pct(self._value("agreement.property"))],
            ["Pydantic and SHACL agreement, real openFDA records", _pct(self._value("agreement.real"))],
            ["Round-trip success (model to RDF to model)", _pct(self._value("roundtrip"))],
            ["Postgres rejects what its DDL claims to enforce", _pct(self._value("postgres.matrix"))],
            ["Declared pydantic_only constraints", self._value("leaks.pydantic_only")],
            ["Constraints the DDL cannot enforce", self._value("leaks.postgres_static")],
            ["Idiomatic patterns rejected by the regex subset", self._value("leaks.regex_subset")],
            ["pySHACL deviations observed", self._value("findings.pyshacl")],
            ["Generation time for all artifacts (median)", f"{self._value('generation.seconds')} s"],
        ]
        return ["## Summary", "", *_table(["Metric", "Value"], rows), ""]

    def _mutation_section(self) -> list[str]:
        rows = self._mutations()
        d = self._details("mutation.detection_rate")
        out = ["## Mutation detection", ""]
        if not rows:
            return [*out, "No mutation suite run recorded yet. Run `make mutate`.", ""]
        out.append(
            f"{d.get('caught_by_expected_gate')} of {d.get('mutations')} mutations were caught by their expected gate"
            f" ({_pct(self._value('mutation.detection_rate'))}); {d.get('caught_by_any_gate')} were caught by at least"
            f" one gate. False-alarm probes: {', '.join(d.get('false_alarm_probes', []))}; false alarms:"
            f" {', '.join(d.get('false_alarms', [])) or 'none'}."
        )
        out.append("")
        table = []
        for r in rows:
            det = r["details"]
            table.append(
                [
                    r["metric"].removeprefix("mutation."),
                    det["title"],
                    det["expected_gate"],
                    ", ".join(det["failed_gates"]) or "none",
                    "yes" if r["value"] else "NO",
                    f"{det['seconds']:.1f}",
                ]
            )
        out += _table(["ID", "Mutation", "Expected gate", "Gates that failed", "As expected", "Seconds"], table)
        out += ["", "Gate evidence (last lines of output) for each caught mutation:", ""]
        for r in rows:
            for gate, text in sorted(r["details"].get("evidence", {}).items()):
                out.append(f"* {r['metric'].removeprefix('mutation.')} / {gate}: `{_cell(text)[:220]}`")
        return [*out, ""]

    def _agreement_section(self) -> list[str]:
        out = ["## Pydantic and SHACL agreement", ""]
        fx = self._details("agreement.fixtures")
        outcomes = fx.get("outcomes", {})
        rows = [
            [group, sum(c.values()), ", ".join(f"{k}: {v}" for k, v in sorted(c.items()))]
            for group, c in outcomes.items()
        ]
        out += [
            f"Curated fixtures: {_pct(self._value('agreement.fixtures'))} agreement over {fx.get('cases')} schema"
            " fixtures (valid plus invalid). Dialect probes are listed separately.",
            "",
        ]
        out += _table(["Group", "Fixtures", "Outcomes"], rows)
        out += ["", "Declared leaks seen in fixtures (Pydantic rejects, SHACL accepts, by declaration):", ""]
        out += [f"* {d['fixture']}: {d['constraint']}" for d in fx.get("declared_leaks", [])] or ["* none"]
        out += ["", "Dialect probes:", ""]
        out += [f"* {p['probe']}: {p['outcome']}. {p['note']}" for p in fx.get("dialect_probes", [])] or ["* none"]
        prop = self._details("agreement.property")
        out += [
            "",
            f"Property-based cases: {_pct(self._value('agreement.property'))} agreement over {prop.get('cases')} cases"
            f" ({prop.get('examples_per_class')} valid examples per class, {prop.get('examples_per_site')} per mutation"
            " site, derandomized).",
            "",
        ]
        by = prop.get("by_perturbation", {})
        out += _table(
            ["Perturbation", "Outcomes"],
            [[k, ", ".join(f"{o}: {n}" for o, n in sorted(v.items()))] for k, v in by.items()],
        )
        dis = prop.get("disagreements", [])
        out += ["", f"Property-based disagreements: {len(dis)}."]
        out += [f"* {d['class']} {d['site']}: pydantic {d.get('pydantic')}, shacl {d.get('shacl')}" for d in dis]
        real = self._details("agreement.real")
        out += [
            "",
            f"Real records ({real.get('source')}): {_pct(self._value('agreement.real'))} agreement over"
            f" {real.get('cases')} candidate records mapped from {real.get('raw_records')} raw records."
            f" Outcomes: {real.get('outcomes')}. Disagreements: {len(real.get('disagreements', []))}.",
        ]
        ds = self._details("agreement.dataset_integrity")
        if ds:
            out += [
                "",
                f"Dataset-level referential integrity of the merged valid fixtures (no reference stubs, so sh:class"
                " checks that referents exist):"
                f" {'conforms' if self._value('agreement.dataset_integrity') else 'fails'}"
                f" over {ds.get('triples')} triples. Pydantic cannot check this per record; Postgres foreign keys can.",
            ]
        return [*out, ""]

    def _roundtrip_section(self) -> list[str]:
        d = self._details("roundtrip")
        return [
            "## Round trip",
            "",
            f"{_pct(self._value('roundtrip'))} of instances survive model to RDF to model, both in memory and through"
            f" Turtle text. Cases: {d.get('cases')}; passed: {d.get('passed')};"
            f" failures: {len(d.get('failures', []))}.",
            "",
        ]

    def _conformance_section(self) -> list[str]:
        out = ["## Real-data conformance", ""]
        rows = []
        notes = []
        for metric, r in sorted(self._latest.items()):
            if not metric.startswith("conformance."):
                continue
            d = r["details"]
            reasons = "; ".join(f"{n} x {reason}" for reason, n in d["top_reasons"][:3]) or "none"
            rows.append([metric.removeprefix("conformance."), d["candidates"], d["valid"], _pct(r["value"]), reasons])
            for note, n in d["ingest_notes"][:3]:
                notes.append(f"* {metric.removeprefix('conformance.')}: {n} x {note}")
        if not rows:
            return [*out, "No conformance run recorded yet.", ""]
        source = next(r["details"]["source"] for m, r in self._latest.items() if m.startswith("conformance."))
        out += [
            f"Source: {source}. A failing real record is a finding about the data or the model; no constraint"
            " was loosened to make records pass.",
            "",
        ]
        out += _table(["Class", "Candidates", "Valid", "Rate", "Top failure reasons"], rows)
        out += ["", "Ingest notes (where the source could not fill a field unambiguously):", "", *notes]
        return [*out, ""]

    def _leak_section(self) -> list[str]:
        out = ["## Leak inventory", "", "### Constraints declared pydantic_only", ""]
        decl = self._details("leaks.pydantic_only").get("declared", [])
        out += _table(["Constraint", "Class", "Reason"], [[d["id"], d["class"], d["reason"]] for d in decl])
        out += ["", "### Constraints the Postgres DDL cannot enforce (static, from the generator)", ""]
        static = self._details("leaks.postgres_static").get("unenforced", [])
        out += _table(
            ["Class", "Field", "Kind", "Reason"],
            [[u["class"], u["field"] or "", u["kind"], u["reason"]] for u in static],
        )
        pg = self._details("postgres.matrix")
        out += ["", "### What Postgres 18 actually did with every invalid fixture", ""]
        if "skipped" in pg:
            out += [f"Skipped: {pg['skipped']}"]
        elif pg:
            rows = pg.get("rows", [])
            leaks = [r for r in rows if r["ddl_claims_enforced"] and not r["rejected"]]
            extra = [r for r in rows if not r["ddl_claims_enforced"] and r["rejected"]]
            out += [
                f"Valid fixtures loaded: {pg.get('valid_loaded')} (failures: {len(pg.get('valid_failed', []))}). Of the"
                f" invalid fixtures whose constraint the DDL claims to enforce, Postgres rejected"
                f" {_pct(self._value('postgres.matrix'))}.",
                "",
                "Accepted although the DDL has a constraint for them (implicit casts of the inserted value):",
                "",
            ]
            out += [f"* {r['fixture']} ({r['violates']})" for r in leaks] or ["* none"]
            out += ["", "Rejected although the DDL does not claim them:", ""]
            out += [f"* {r['fixture']} ({r['violates']}) by {r['by']}" for r in extra] or ["* none"]
            out += ["", "Probes:", ""]
            out += [
                f"* {p['probe']}: {'rejected' if p['rejected'] else 'accepted'} ({p['by']})"
                for p in pg.get("probes", [])
            ]
        out += ["", "### Patterns outside the safe regex subset", ""]
        catalog = self._details("leaks.regex_subset").get("idiomatic_patterns", [])
        out += ["Idiomatic patterns a developer would write for this model, checked against the subset:", ""]
        out += _table(
            ["Purpose", "Pattern", "In subset", "Reason"],
            [[c["purpose"], f"`{c['pattern']}`", "yes" if c["accepted"] else "no", c["reason"] or ""] for c in catalog],
        )
        out += ["", "### Validator implementation findings (pySHACL)", ""]
        probes = self._details("findings.pyshacl").get("probes", [])
        out += [f"* {p['id']}: {'observed' if p['observed'] else 'not observed'}. {p['description']}" for p in probes]
        return [*out, ""]

    def _size_section(self) -> list[str]:
        src = self._details("size.source")
        gen = self._details("size.generated").get("artifacts", {})
        out = [
            "## Size and generation time",
            "",
            f"Source: `{src.get('file')}`, {src.get('lines_total')} lines ({src.get('lines_non_blank_non_comment')}"
            f" non-blank, non-comment), {src.get('classes')} classes ({src.get('concrete_classes')} concrete),"
            f" {src.get('enums')} enums, {src.get('fields')} fields, {src.get('rules')} rules,"
            f" {src.get('pydantic_only')} pydantic_only validators, {src.get('constraint_sites')} constraint sites.",
            "",
        ]
        total = self._value("size.generated")
        out += _table(
            ["Artifact", "Lines", "Bytes", "Triples"],
            [[name, g["lines"], g["bytes"], g.get("triples", "")] for name, g in gen.items()],
        )
        if total and src.get("lines_total"):
            out += ["", f"Generated lines per source line: {total / src['lines_total']:.1f}."]
        t = self._details("generation.seconds")
        out += [
            "",
            f"Generation time (median of {t.get('repeats')}): analyze {t.get('analyze')} s, per artifact"
            f" {t.get('per_artifact')}, total {self._value('generation.seconds')} s.",
            "",
        ]
        return out

    def _provenance(self) -> list[str]:
        rows = [
            [m, r["run_id"], r["git_sha"][:12], r["schema_version"], r["timestamp"][:19]]
            for m, r in sorted(self._latest.items())
        ]
        return ["## Provenance", "", *_table(["Metric", "Run", "Git SHA", "Schema", "UTC time"], rows), ""]

    # -----------------------------------------------------------------------------------------------

    def _pov(self) -> list[str]:
        detection = self._value("mutation.detection_rate")
        false_alarms = self._details("mutation.detection_rate").get("false_alarms", [])
        agreement = [self._value(m) for m in ("agreement.fixtures", "agreement.property", "agreement.real")]
        roundtrip = self._value("roundtrip")
        leaks = {
            "pydantic_only": self._value("leaks.pydantic_only") or 0,
            "postgres": self._value("leaks.postgres_static") or 0,
            "regex": self._value("leaks.regex_subset") or 0,
            "pyshacl": self._value("findings.pyshacl") or 0,
        }
        sync = detection == 1 and not false_alarms and all(a == 1 for a in agreement) and roundtrip == 1
        verdict = "holds" if sync and not any(leaks.values()) else "partly holds" if sync else "fails"
        pg = self._details("postgres.matrix")
        coerced = [r for r in pg.get("rows", []) if r["ddl_claims_enforced"] and not r["rejected"]]
        dialect = [
            p for p in self._details("agreement.fixtures").get("dialect_probes", []) if p["outcome"] == "disagree"
        ]
        conformance = {
            m.removeprefix("conformance."): r["value"] for m, r in self._latest.items() if m.startswith("conformance.")
        }
        weakest = sorted(conformance.items(), key=lambda kv: kv[1])[:3]
        catalog = len(self._details("leaks.regex_subset").get("idiomatic_patterns", []))
        real_cause = (
            "Pydantic and SHACL judged every real record identically, so these failures are about the source data"
            " and the model (keys, enums, rules), not about drift between artifacts."
            if agreement[2] == 1
            else "Pydantic and SHACL disagreed on some real records, so part of these failures is projection drift."
        )
        dialect_text = (
            f"{len(dialect)} dialect probes disagree (Pydantic and SHACL read the same pattern differently)."
            if dialect
            else "no dialect probe disagrees."
        )
        out = [
            "## What this means for the PoV",
            "",
            f"**Verdict: H6 {verdict}.** Rule: it holds if every mutation is caught by its expected gate with no false"
            " alarm, Pydantic and SHACL agree on every fixture, property case and real record, the round trip is"
            " lossless, and the leak inventory is empty. It partly holds if everything but the last condition is met."
            " Otherwise it fails.",
            "",
            f"* Sync between the one source and its projections is enforced: {_pct(detection)} of mutations were caught"
            f" by the intended gate, false alarms: {len(false_alarms)}.",
            f"* Pydantic and SHACL reach the same verdict: fixtures {_pct(agreement[0])}, property cases"
            f" {_pct(agreement[1])}, real records {_pct(agreement[2])}. Round trip: {_pct(roundtrip)}.",
            f"* It holds only inside a projectable subset. Leaks: {leaks['pydantic_only']} pydantic_only constraints,"
            f" {leaks['postgres']} constraints the DDL cannot express, {len(coerced)} invalid fixtures Postgres"
            f" accepted through implicit casts, {leaks['regex']} of {catalog} idiomatic regexes outside the safe"
            " subset.",
            f"* Agreement also depends on the validator implementation: {leaks['pyshacl']} pySHACL deviations from the"
            f" SHACL spec were observed, and {dialect_text}",
            "* Lowest real-data conformance: "
            + ", ".join(f"{name} {_pct(rate)}" for name, rate in weakest)
            + f". {real_cause}",
            "",
        ]
        return out
